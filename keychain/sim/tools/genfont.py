#!/usr/bin/env python3
"""Generate bitmap font data for the keychain sim from Liberation Sans.

For each TFT_eSPI font id (1,2,4,6) renders ASCII 32..126 with PIL and
emits a C header with per-glyph advance + packed 1-bit bitmaps.
Cell height = ascent + descent (anchor 'la': ascender top at y=0).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT_PATH = "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf"
# font id -> render size (px). Font 6 is 44 not 48: at 48px the price
# "$62,601" is wider than the sketch's 166px fit threshold and the
# sketch would drop to font 4; at 44px it fits, matching the author's
# intent (big price in the big font). See README note in final report.
SIZES = {1: 8, 2: 16, 4: 26, 6: 44}
# Horizontal scale per font. Font 2 is squeezed 0.78x: the real
# TFT_eSPI 16px font is narrow (~7px/char) and the sketch's 32px
# control buttons expect "Line"/"Cndl"/"USD"/"Auth" to fit at font 2
# (only "Price" is meant to drop to font 1, per the sketch comment).
# Liberation Sans at 16px is ~9px/char, so without the squeeze those
# labels would all drop to the tiny font 1.
XSCALE = {1: 1.0, 2: 0.78, 4: 1.0, 6: 1.0}

out = []
out.append("// Generated by tools/genfont.py from LiberationSans-Regular.ttf")
out.append("// ASCII 32..126, 1-bit bitmaps, cell height = ascent+descent.")
out.append("#pragma once")
out.append("#include <stdint.h>")
out.append("")
out.append("struct SimGlyph { uint8_t adv; uint32_t off; };  // off = bit offset into bits[]")
out.append("struct SimFont { uint8_t cell_h; const SimGlyph *glyphs; const uint8_t *bits; };")
out.append("")

for fid, size in SIZES.items():
    font = ImageFont.truetype(FONT_PATH, size)
    ascent, descent = font.getmetrics()
    cell_h = ascent + descent
    advs = []
    glyph_bits = []  # list of (adv, list of bits row-major)
    bitstream = []
    bitpos = 0
    offs = []
    for code in range(32, 127):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        if adv < 1:
            adv = 1
        img = Image.new("L", (adv, cell_h), 0)
        d = ImageDraw.Draw(img)
        d.text((0, 0), ch, font=font, fill=255, anchor="la")
        xs = XSCALE[fid]
        if xs != 1.0:
            nw = max(1, int(round(adv * xs)))
            img = img.resize((nw, cell_h), Image.LANCZOS)
            img = img.point(lambda v: 255 if v > 128 else 0)
            adv = nw
        px = img.load()
        bits = []
        for y in range(cell_h):
            for x in range(adv):
                bits.append(1 if px[x, y] > 128 else 0)
        offs.append(bitpos)
        advs.append(adv)
        bitstream.extend(bits)
        bitpos += len(bits)
    # pack bits MSB-first
    packed = bytearray()
    for i in range(0, len(bitstream), 8):
        b = 0
        for j in range(8):
            if i + j < len(bitstream) and bitstream[i + j]:
                b |= 1 << (7 - j)
        packed.append(b)
    out.append(f"static const uint8_t font{fid}_bits[] = {{")
    for i in range(0, len(packed), 20):
        out.append("  " + ",".join(str(b) for b in packed[i:i + 20]) + ",")
    out.append("};")
    out.append(f"static const SimGlyph font{fid}_glyphs[95] = {{")
    for k, code in enumerate(range(32, 127)):
        out.append(f"  {{{advs[k]}, {offs[k]}}},  // {code} '{chr(code)}'")
    out.append("};")
    out.append(f"static const SimFont simFont{fid} = {{{cell_h}, font{fid}_glyphs, font{fid}_bits}};")
    out.append("")
    print(f"font {fid}: size={size} cell_h={cell_h} bits={len(packed)} bytes", file=sys.stderr)

path = sys.argv[1] if len(sys.argv) > 1 else "fontdata.h"
with open(path, "w") as f:
    f.write("\n".join(out))
print(f"wrote {path}", file=sys.stderr)
